def convert_stations():
    """
    Reads stations.csv → list of { id, lat, lon, elev, depth } dicts.
    """
    csv_path = RAW_DIR / "stations.csv"
    if not csv_path.exists() or csv_path.stat().st_size == 0:
        print(f"{len(STATIONS_FALLBACK)} stations (from built-in fallback; stations.csv empty)")
        return [dict(st) for st in STATIONS_FALLBACK]
    if not csv_path.exists():
        print(f"  [SKIP] {csv_path.name} not found")
        return []

    print(f"  Reading {csv_path.name} ...", end=" ", flush=True)
    df = pd.read_csv(csv_path).fillna("")
    df.columns = [c.strip().lower() for c in df.columns]

    result = [
        {
            "id":    f"{row.network}.{row.station}",
            "lat":   round(float(row.latitude),  6),
            "lon":   round(float(row.longitude), 6),
            "elev":  round(float(row.elevation), 1),
            "depth": round(float(row.depth),     1),
        }
        for row in df.itertuples()
    ]

    print(f"{len(result)} stations")
    return result


# 5. Metadata

def build_meta(events):
    """
    Computes bounding box and time range from the events list.
    Stored in META constant in data.js — app.js reads this instead
    of using hardcoded values, so adding a new dataset just means
    re-running the script.
    """
    if not events:
        return {}
    return {
        "name":       "Rhône Glacier Icequakes 2020",
        "domain":     "seismic",
        "axes":       {"x": "East (m)", "y": "North (m)", "z": "Depth (m)"},
        "q_label":    "Semblance",
        "date_range": "Jul – Aug 2020",
        "has_meteo":  True,
        "count":   len(events),
        "t_min":   events[0]["t"],
        "t_max":   events[-1]["t"],
        "x_range": [min(e["x"] for e in events), max(e["x"] for e in events)],
        "y_range": [min(e["y"] for e in events), max(e["y"] for e in events)],
        "z_range": [min(e["z"] for e in events), max(e["z"] for e in events)],
    }


# 6. Write public/data.js

def build_dem(grid_n=200):
    """
    Builds the glacier SURFACE and BEDROCK grids from the real Rhone Glacier
    DEM (data/raw/DEM), resampled onto the event footprint.

    The DEM ships as six np.savetxt text arrays on an 844 x 385 curvilinear
    lat/lon grid:
        lat_dem_np / lon_dem_np / zv_dem_np   -> ice surface elevation [m a.s.l.]
        zv_bed_np                             -> bedrock elevation     [m a.s.l.]
                                                 (on the same lat/lon grid)

    Steps:
      1. fit the (lat, lon) -> (east_shift, north_shift) transform from the
         detections CSV, which carries BOTH coordinate systems;
      2. project every DEM node into that metric system;
      3. resample both layers onto a regular grid_n x grid_n grid spanning the
         event extent (linear, nearest-neighbour fill for any gap).

    Returns (surface, bedrock), each a dict consumed by app.js:
        { "n", "x_min", "x_max", "y_min", "y_max", "z_min", "z_max", "z": [...] }
    with z in the event convention (z = -elevation), row-major.

    NOTE: this replaces the earlier station-interpolation approach. Fitting a
    surface through only 14 station elevations left ~97% of the grid clamped
    flat and produced a plate-with-a-crater artefact rather than terrain.
    """
    det_path = RAW_DIR / "detections_jittered.csv"
    dem_dir  = RAW_DIR / "DEM"
    # lat_bed_np / lon_bed_np were byte-identical copies of lat_dem_np /
    # lon_dem_np (both DEMs are sampled on the same lat/lon grid) and were
    # never loaded - only the four files below are read, at ~8 MB each.
    need = ["lat_dem_np", "lon_dem_np", "zv_dem_np", "zv_bed_np"]
    if not det_path.exists() or not all((dem_dir / f).exists() for f in need):
        print("  [SKIP] DEM needs detections CSV + data/raw/DEM/*")
        return None, None

    from scipy.interpolate import griddata

    print("  Fitting lat/lon -> east/north transform ...", end=" ", flush=True)
    det = pd.read_csv(det_path)
    A = np.column_stack([det.lon, det.lat, np.ones(len(det))])
    ce, *_ = np.linalg.lstsq(A, det.east_shift.values,  rcond=None)
    cn, *_ = np.linalg.lstsq(A, det.north_shift.values, rcond=None)
    res_e = float(np.std(det.east_shift.values  - A @ ce))
    res_n = float(np.std(det.north_shift.values - A @ cn))
    print(f"residual {res_e:.3f} / {res_n:.3f} m")

    print("  Loading DEM rasters ...", end=" ", flush=True)
    lat = np.loadtxt(dem_dir / "lat_dem_np"); lon = np.loadtxt(dem_dir / "lon_dem_np")
    z_s = np.loadtxt(dem_dir / "zv_dem_np");  z_b = np.loadtxt(dem_dir / "zv_bed_np")
    print(f"{lat.shape[0]}x{lat.shape[1]} nodes")

    E = ce[0] * lon + ce[1] * lat + ce[2]
    N = cn[0] * lon + cn[1] * lat + cn[2]

    ex0, ex1 = float(det.east_shift.min()),  float(det.east_shift.max())
    ny0, ny1 = float(det.north_shift.min()), float(det.north_shift.max())
    margin = 120.0
    sel = (E > ex0 - margin) & (E < ex1 + margin) & (N > ny0 - margin) & (N < ny1 + margin)
    pts = np.column_stack([E[sel], N[sel]])
    print(f"  {sel.sum()} DEM nodes inside the event footprint")

    gx = np.linspace(ex0, ex1, grid_n); gy = np.linspace(ny0, ny1, grid_n)
    GX, GY = np.meshgrid(gx, gy)

    def resample(src):
        out = griddata(pts, src[sel], (GX, GY), method="linear")
        bad = np.isnan(out)
        if bad.any():
            out[bad] = griddata(pts, src[sel], (GX[bad], GY[bad]), method="nearest")
        return out

    print(f"  Resampling {grid_n}x{grid_n} surface + bedrock ...", end=" ", flush=True)
    surf = resample(z_s); bed = resample(z_b)
    print("done")

    def pack(arr):
        z = (-arr).ravel()          # event convention: z = -elevation
        return {
            "n": grid_n,
            "x_min": round(ex0, 1), "x_max": round(ex1, 1),
            "y_min": round(ny0, 1), "y_max": round(ny1, 1),
            "z_min": round(float(z.min()), 1), "z_max": round(float(z.max()), 1),
            "z": [round(float(v), 1) for v in z],
        }

    thick = surf - bed
    print(f"  ice surface {surf.min():.0f}..{surf.max():.0f} m, "
          f"bedrock {bed.min():.0f}..{bed.max():.0f} m, "
          f"thickness median {np.median(thick):.0f} m")
    return pack(surf), pack(bed), (ce, cn)


def write_data_js(events, meteo, runoff, stations, surface=None, bedrock=None):
    """
    Serialises all arrays as JavaScript constants into public/data.js.

    The browser loads this with <script src="data.js">.
    After loading, app.js can use EV, METEO, RUNOFF, STATIONS, META directly —
    no server, no build step, no fetch() call needed.
    """
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    meta = build_meta(events)

    content = "\n".join([
        "// ─────────────────────────────────────────────────────────────────",
        "// data.js — auto-generated by scripts/convert_data.py",
        "// DO NOT EDIT BY HAND — re-run the script to regenerate.",
        "// ─────────────────────────────────────────────────────────────────",
        "",
        "// Metadata: name, count, time range, spatial bounding box",
        f"const META     = {dump(meta)};",
        "",
        "// Events sorted by time: [ { t, x, y, z, q }, ... ]",
        f"const EV       = {dump(events)};",
        "",
        "// Meteo hourly: [ { t, temp, precip }, ... ]",
        f"const METEO    = {dump(meteo)};",
        "",
        "// Runoff hourly: [ { t, v }, ... ]",
        f"const RUNOFF   = {dump(runoff)};",
        "",
        "// Seismic stations: [ { id, lat, lon, elev, depth }, ... ]",
        f"const STATIONS = {dump(stations)};",
        "",
        "// Glacier ice-surface DEM grid (null for datasets without one)",
        f"const SURFACE  = {dump(surface)};",
        "",
        "// Bedrock DEM grid beneath the ice (null for datasets without one)",
        f"const BEDROCK  = {dump(bedrock)};",
        "",
    ])

    OUT_FILE.write_text(content, encoding="utf-8")

    size_kb = OUT_FILE.stat().st_size / 1024
    print(f"\n  ✓  Written: {OUT_FILE}")
    print(f"     Size:    {size_kb:.1f} KB")

# 7. Lorenz attractor
def generate_lorenz(n_steps=22000):
    """Single long Lorenz trajectory — σ=10, ρ=28, β=8/3."""
    print(f"  Integrating Lorenz system ({n_steps} steps) ...", end=" ", flush=True)
    from scipy.integrate import odeint

    sigma, rho, beta = 10.0, 28.0, 8.0 / 3.0

    def lorenz(state, t):
        x, y, z = state
        return [sigma*(y-x), x*(rho-z)-y, x*y-beta*z]

    # burn-in to land on the attractor
    ic = odeint(lorenz, [0.1, 0.0, 0.0], np.linspace(0, 25, 2500))[-1].tolist()
    t_main = np.linspace(0, float(n_steps) / 100, n_steps)
    sol = odeint(lorenz, ic, t_main)

    # quality = inverse normalised speed (slow = more stable = higher q)
    diffs = np.linalg.norm(np.diff(sol, axis=0), axis=1)
    q_vals = 1.0 - diffs / (diffs.max() or 1.0)
    q_pad  = np.append(q_vals, q_vals[-1])

    events = [
        {"t": round(float(t_main[i]), 3),
         "x": round(float(sol[i, 0]), 3),
         "y": round(float(sol[i, 1]), 3),
         "z": round(float(sol[i, 2]), 3),
         "q": round(float(q_pad[i]),  4)}
        for i in range(n_steps)
    ]
    print(f"{n_steps} points")

    xs = [e["x"] for e in events]; ys = [e["y"] for e in events]; zs = [e["z"] for e in events]
    meta = {
        "name": "Lorenz Attractor (Deterministic Chaos)", "domain": "orbital",
        "axes": {"x": "X", "y": "Y", "z": "Z"}, "q_label": "Trajectory stability",
        "date_range": "Numerical simulation  σ=10  ρ=28  β=8/3", "has_meteo": False,
        "count": len(events), "t_min": events[0]["t"], "t_max": events[-1]["t"],
        "x_range": [min(xs), max(xs)], "y_range": [min(ys), max(ys)],
        "z_range": [min(zs), max(zs)],
    }
    return {"meta": meta, "events": events, "meteo": []}

# 8. Synthetic UK traffic incidents
def generate_traffic(n_events=9000, seed=42):
    """Synthetic UK road-accident data with rush-hour temporal patterns."""
    print(f"  Generating {n_events} synthetic traffic incidents ...", end=" ", flush=True)
    rng = np.random.default_rng(seed)

    roads = [
        (np.array([-40000,-28000]), np.array([42000, 30000]), 0.30),
        (np.array([  3000,-36000]), np.array([ 3000, 36000]), 0.25),
        (np.array([-44000,  1000]), np.array([44000,  1000]), 0.22),
        (np.array([-22000,-22000]), np.array([22000, 22000]), 0.13),
        (np.array([-16000, 12000]), np.array([26000,-14000]), 0.10),
    ]
    weights = np.array([r[2] for r in roads]); weights /= weights.sum()
    t_start = 1640995200   # 2022-01-01 00:00 UTC
    events = []

    for _ in range(n_events):
        ri = rng.choice(len(roads), p=weights)
        s, e = roads[ri][0], roads[ri][1]
        direction = e - s
        norm_len = float(np.linalg.norm(direction)) or 1.0
        perp = np.array([-direction[1], direction[0]]) / norm_len
        pos = s + rng.uniform(0, 1)*direction + perp*rng.normal(0, 400)

        day = int(rng.integers(0, 365))
        is_wknd = (day % 7) >= 5
        hr_draw = float(rng.uniform())
        if   is_wknd:         hour = float(rng.normal(12.5, 3.5))
        elif hr_draw < 0.25:  hour = float(rng.normal(8.0,  0.9))
        elif hr_draw < 0.55:  hour = float(rng.normal(17.5, 1.1))
        elif hr_draw < 0.80:  hour = float(rng.uniform(10, 16))
        else:                 hour = float(rng.uniform(0, 6))
        hour = max(0.0, min(23.99, hour))
        ts = t_start + day*86400 + int(hour*3600)
        sev = int(rng.choice([1, 2, 3], p=[0.04, 0.22, 0.74]))
        events.append({"t": float(ts), "x": round(float(pos[0]), 1),
                       "y": round(float(pos[1]), 1), "z": 0.0,
                       "q": round((4 - sev) / 3.0, 4)})

    events.sort(key=lambda ev: ev["t"])
    print(f"{len(events)} events")

    xs = [e["x"] for e in events]; ys = [e["y"] for e in events]
    meta = {
        "name": "UK Road Traffic Incidents (Synthetic)", "domain": "traffic",
        "axes": {"x": "Longitude (proj.)", "y": "Latitude (proj.)", "z": "(flat)"},
        "q_label": "Severity (inverse)", "date_range": "Jan – Dec 2022", "has_meteo": False,
        "count": len(events), "t_min": events[0]["t"], "t_max": events[-1]["t"],
        "x_range": [min(xs), max(xs)], "y_range": [min(ys), max(ys)], "z_range": [0.0, 0.0],
    }
    return {"meta": meta, "events": events, "meteo": []}


