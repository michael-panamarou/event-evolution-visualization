#!/usr/bin/env python3
"""
convert_data.py
===============
Converts raw CSV datasets into the unified JSON format
used by the browser visualisation (public/data.js).

Usage
-----
    python scripts/convert_data.py                  # convert all datasets
    python scripts/convert_data.py --sample 5000    # limit to N events (for dev)
    python scripts/convert_data.py --help

Expected raw files (data/raw/)
------------------------------
    detections_jittered.csv   — seismic events  (required)
    meteo.csv                 — meteorological  (optional)
    runoff.csv                — water runoff    (optional)
    stations.csv              — sensor locations (optional)

Output
------
    public/data.js  — JS file exposing: EV, METEO, RUNOFF, STATIONS, META

Adding a new dataset
--------------------
    1. Put your CSV in data/raw/
    2. Make sure it has columns for time, x/east, y/north, z/depth, q/quality
    3. Add a converter function following the pattern of convert_events()
    4. Call it in main() and pass the result to write_data_js()
    5. Run this script again
"""

import argparse, json, sys
from pathlib import Path
import numpy as np

import pandas as pd

# Paths
ROOT     = Path(__file__).parent.parent   # project root (icequake-viz/)
RAW_DIR  = ROOT / "data" / "raw"
OUT_DIR  = ROOT / "public"
OUT_FILE = OUT_DIR / "data.js"

# helper functions
# helper functions used by the two new datasets
def dump(obj):
    return json.dumps(obj, separators=(",", ":"), ensure_ascii=False)

def write_js_const(path, const_name, value):
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"// auto-generated by scripts/convert_data.py — do not edit\n"
        f"const {const_name} = {dump(value)};\n",
        encoding="utf-8")
    kb = path.stat().st_size / 1024
    print(f"     → {path.name}  ({kb:.0f} KB)")


# 1. Events

def convert_events(sample = None):
    """
    Reads detections_jittered.csv and returns a list of compact event dicts:
        { t: unix_seconds, x: metres, y: metres, z: metres, q: 0-1 }

    t = Unix timestamp (float seconds since 1970-01-01)
    x = east_shift  — horizontal position in metres east of reference point
    y = north_shift — horizontal position in metres north of reference point
    z = depth_ellipsoid — depth in metres (negative values = below surface)
    q = semblance   — detection quality score between 0 and 1
    """
    csv_path = RAW_DIR / "detections_jittered.csv"
    if not csv_path.exists():
        print(f"  [SKIP] {csv_path.name} not found")
        return []

    print(f"  Reading {csv_path.name} ...", end=" ", flush=True)
    df = pd.read_csv(csv_path)

    # Normalise column names: lowercase, strip spaces
    df.columns = [c.strip().lower() for c in df.columns]

    # Verify required columns exist
    required = {"time", "east_shift", "north_shift", "depth_ellipsoid", "semblance"}
    missing  = required - set(df.columns)
    if missing:
        print(f"\n  [ERROR] Missing columns: {missing}")
        print(f"  Available columns: {list(df.columns)}")
        sys.exit(1)

    # Parse time string → proper datetime object
    df["time"] = pd.to_datetime(df["time"], utc=True)

    # Sort oldest → newest
    df = df.sort_values("time").reset_index(drop=True)

    # Optional random sample (useful during development)
    total = len(df)
    if sample and sample < total:
        df = (df.sample(sample, random_state=42)
                .sort_values("time")
                .reset_index(drop=True))
        print(f"sampled {sample} of {total} rows")
    else:
        print(f"{total} rows")

    # Build output - one compact dict per event
    events = [
        {
            "t": round(row.time.timestamp(), 1),   # datetime → float seconds
            "x": round(float(row.east_shift),  1), # metres east
            "y": round(float(row.north_shift), 1), # metres north
            "z": round(float(row.depth_ellipsoid), 1), # metres depth
            "q": round(float(row.semblance), 4),   # quality 0-1
        }
        for row in df.itertuples()
        if (pd.notna(row.east_shift) and pd.notna(row.north_shift)
            and pd.notna(row.depth_ellipsoid) and pd.notna(row.semblance))
    ]

    print(f"  → {len(events)} events | "
          f"time: {df.time.min().date()} – {df.time.max().date()} | "
          f"depth: {df.depth_ellipsoid.min():.0f} - {df.depth_ellipsoid.max():.0f} m | "
          f"east: {df.east_shift.min():.0f} - {df.east_shift.max():.0f} m")

    return events


# 2. Meteo

def convert_meteo():
    """
    Reads meteo.csv → list of { t, temp, precip } dicts.
    Resampled to hourly (raw is every 10 min — reduces size 6x).
    """
    csv_path = RAW_DIR / "meteo.csv"
    if not csv_path.exists():
        print(f"  [SKIP] {csv_path.name} not found")
        return []

    print(f"  Reading {csv_path.name} ...", end=" ", flush=True)
    df = pd.read_csv(csv_path)
    df.columns = [c.strip().lower().replace(" ", "_") for c in df.columns]
    df["time"] = pd.to_datetime(df["time"])

    # Resample: group by hour, take mean value in each hour
    df = (df.set_index("time")
            .resample("1h")
            .mean(numeric_only=True)
            .reset_index())

    result = [
        {
            "t":      int(row.time.timestamp()),
            "temp":   round(float(row.temperature), 1)  if pd.notna(row.temperature)  else None,
            "precip": round(float(row.precipitation), 2) if pd.notna(row.precipitation) else 0.0,
        }
        for row in df.itertuples()
        if pd.notna(row.temperature)
    ]

    print(f"{len(result)} hourly entries")
    return result


# 3. Runoff

def convert_runoff():
    """
    Reads runoff.csv → list of { t, v } dicts.
    Resampled to hourly.
    """
    csv_path = RAW_DIR / "runoff.csv"
    if not csv_path.exists():
        print(f"  [SKIP] {csv_path.name} not found")
        return []

    print(f"  Reading {csv_path.name} ...", end=" ", flush=True)
    df = pd.read_csv(csv_path)
    df.columns = [c.strip().lower().replace(" ", "_") for c in df.columns]
    df["time"] = pd.to_datetime(df["time"])

    df = (df.set_index("time")
            .resample("1h")
            .mean(numeric_only=True)
            .reset_index())

    # Pick the first non-time column as the value
    val_col = [c for c in df.columns if c != "time"][0]

    result = [
        {"t": int(row.time.timestamp()), "v": round(float(getattr(row, val_col)), 3)}
        for row in df.itertuples()
        if pd.notna(getattr(row, val_col))
    ]

    print(f"{len(result)} hourly entries  (column: '{val_col}')")
    return result


# 4. Stations

def convert_stations():
    """
    Reads stations.csv → list of { id, lat, lon, elev, depth } dicts.
    """
    csv_path = RAW_DIR / "stations.csv"
    if not csv_path.exists():
        print(f"  [SKIP] {csv_path.name} not found")
        return []

    print(f"  Reading {csv_path.name} ...", end=" ", flush=True)
    df = pd.read_csv(csv_path).fillna("")
    df.columns = [c.strip().lower() for c in df.columns]

    result = [
        {
            "id":    f"{row.network}.{row.station}",
            "lat":   round(float(row.latitude),  6),
            "lon":   round(float(row.longitude), 6),
            "elev":  round(float(row.elevation), 1),
            "depth": round(float(row.depth),     1),
        }
        for row in df.itertuples()
    ]

    print(f"{len(result)} stations")
    return result


# 5. Metadata

def build_meta(events):
    """
    Computes bounding box and time range from the events list.
    Stored in META constant in data.js — app.js reads this instead
    of using hardcoded values, so adding a new dataset just means
    re-running the script.
    """
    if not events:
        return {}
    return {
        "name":       "Rhône Glacier Icequakes 2020",
        "domain":     "seismic",
        "axes":       {"x": "East (m)", "y": "North (m)", "z": "Depth (m)"},
        "q_label":    "Semblance",
        "date_range": "Jul – Aug 2020",
        "has_meteo":  True,
        "count":   len(events),
        "t_min":   events[0]["t"],
        "t_max":   events[-1]["t"],
        "x_range": [min(e["x"] for e in events), max(e["x"] for e in events)],
        "y_range": [min(e["y"] for e in events), max(e["y"] for e in events)],
        "z_range": [min(e["z"] for e in events), max(e["z"] for e in events)],
    }


# 6. Write public/data.js

def build_surface(grid_n=48):
    """
    Interpolates the glacier surface from the 14 station elevations.

    There is no DEM raster in the dataset, but every station records a
    surface elevation. We:
      1. fit the (lat, lon) -> (east_shift, north_shift) transform from the
         detections CSV (which contains BOTH coordinate systems), so stations
         can be placed in the same metric space as the events;
      2. convert each station elevation to the event z-convention (z = -elev,
         matching the negative 'depth_ellipsoid' the events use);
      3. interpolate those scattered points onto a regular grid_n x grid_n
         grid spanning the event east/north extent, using a radial basis
         function; values are clamped to the observed station range so the
         extrapolated corners (the station footprint is smaller than the full
         event extent) cannot diverge.

    Returns a dict consumed by app.js to build a semi-transparent mesh:
        { "n", "x_min", "x_max", "y_min", "y_max", "z_min", "z_max", "z": [...] }
    where z is a row-major grid_n*grid_n array of z-values (event convention).
    """
    det_path = RAW_DIR / "detections_jittered.csv"
    st_path  = RAW_DIR / "stations.csv"
    if not det_path.exists() or not st_path.exists():
        print("  [SKIP] surface needs detections + stations CSV")
        return None

    print("  Fitting lat/lon -> east/north transform ...", end=" ", flush=True)
    det = pd.read_csv(det_path)
    A = np.column_stack([det["lon"].values, det["lat"].values, np.ones(len(det))])
    ce, *_ = np.linalg.lstsq(A, det["east_shift"].values,  rcond=None)
    cn, *_ = np.linalg.lstsq(A, det["north_shift"].values, rcond=None)

    st = pd.read_csv(st_path)
    As = np.column_stack([st["longitude"].values, st["latitude"].values, np.ones(len(st))])
    sx = As @ ce                      # station east
    sy = As @ cn                      # station north
    sz = -st["elevation"].values      # event z-convention (negative up)
    print(f"{len(st)} stations placed")

    # Grid spans the full event extent so the surface covers the whole scene
    x_min, x_max = float(det["east_shift"].min()),  float(det["east_shift"].max())
    y_min, y_max = float(det["north_shift"].min()), float(det["north_shift"].max())

    print(f"  Interpolating {grid_n}x{grid_n} surface grid ...", end=" ", flush=True)
    from scipy.interpolate import Rbf
    rbf = Rbf(sx, sy, sz, function="multiquadric", smooth=1.0)

    gx = np.linspace(x_min, x_max, grid_n)
    gy = np.linspace(y_min, y_max, grid_n)
    GX, GY = np.meshgrid(gx, gy)
    GZ = rbf(GX.ravel(), GY.ravel())

    # Clamp to observed range (+/- small margin) to tame extrapolated corners
    z_lo, z_hi = float(sz.min()), float(sz.max())
    margin = 0.15 * (z_hi - z_lo)
    GZ = np.clip(GZ, z_lo - margin, z_hi + margin)

    print(f"z {GZ.min():.0f}..{GZ.max():.0f} m")
    return {
        "n":     grid_n,
        "x_min": round(x_min, 1), "x_max": round(x_max, 1),
        "y_min": round(y_min, 1), "y_max": round(y_max, 1),
        "z_min": round(float(GZ.min()), 1), "z_max": round(float(GZ.max()), 1),
        "z":     [round(float(v), 1) for v in GZ.ravel()],
    }


def write_data_js(events, meteo, runoff, stations, surface=None):
    """
    Serialises all arrays as JavaScript constants into public/data.js.

    The browser loads this with <script src="data.js">.
    After loading, app.js can use EV, METEO, RUNOFF, STATIONS, META directly —
    no server, no build step, no fetch() call needed.
    """
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    meta = build_meta(events)

    content = "\n".join([
        "// ─────────────────────────────────────────────────────────────────",
        "// data.js — auto-generated by scripts/convert_data.py",
        "// DO NOT EDIT BY HAND — re-run the script to regenerate.",
        "// ─────────────────────────────────────────────────────────────────",
        "",
        "// Metadata: name, count, time range, spatial bounding box",
        f"const META     = {dump(meta)};",
        "",
        "// Events sorted by time: [ { t, x, y, z, q }, ... ]",
        f"const EV       = {dump(events)};",
        "",
        "// Meteo hourly: [ { t, temp, precip }, ... ]",
        f"const METEO    = {dump(meteo)};",
        "",
        "// Runoff hourly: [ { t, v }, ... ]",
        f"const RUNOFF   = {dump(runoff)};",
        "",
        "// Seismic stations: [ { id, lat, lon, elev, depth }, ... ]",
        f"const STATIONS = {dump(stations)};",
        "",
        "// Interpolated glacier surface grid (null for datasets without one)",
        f"const SURFACE  = {dump(surface)};",
        "",
    ])

    OUT_FILE.write_text(content, encoding="utf-8")

    size_kb = OUT_FILE.stat().st_size / 1024
    print(f"\n  ✓  Written: {OUT_FILE}")
    print(f"     Size:    {size_kb:.1f} KB")

# 7. Lorenz attractor
def generate_lorenz(n_steps=22000):
    """Single long Lorenz trajectory — σ=10, ρ=28, β=8/3."""
    print(f"  Integrating Lorenz system ({n_steps} steps) ...", end=" ", flush=True)
    from scipy.integrate import odeint

    sigma, rho, beta = 10.0, 28.0, 8.0 / 3.0

    def lorenz(state, t):
        x, y, z = state
        return [sigma*(y-x), x*(rho-z)-y, x*y-beta*z]

    # burn-in to land on the attractor
    ic = odeint(lorenz, [0.1, 0.0, 0.0], np.linspace(0, 25, 2500))[-1].tolist()
    t_main = np.linspace(0, float(n_steps) / 100, n_steps)
    sol = odeint(lorenz, ic, t_main)

    # quality = inverse normalised speed (slow = more stable = higher q)
    diffs = np.linalg.norm(np.diff(sol, axis=0), axis=1)
    q_vals = 1.0 - diffs / (diffs.max() or 1.0)
    q_pad  = np.append(q_vals, q_vals[-1])

    events = [
        {"t": round(float(t_main[i]), 3),
         "x": round(float(sol[i, 0]), 3),
         "y": round(float(sol[i, 1]), 3),
         "z": round(float(sol[i, 2]), 3),
         "q": round(float(q_pad[i]),  4)}
        for i in range(n_steps)
    ]
    print(f"{n_steps} points")

    xs = [e["x"] for e in events]; ys = [e["y"] for e in events]; zs = [e["z"] for e in events]
    meta = {
        "name": "Lorenz Attractor (Deterministic Chaos)", "domain": "orbital",
        "axes": {"x": "X", "y": "Y", "z": "Z"}, "q_label": "Trajectory stability",
        "date_range": "Numerical simulation  σ=10  ρ=28  β=8/3", "has_meteo": False,
        "count": len(events), "t_min": events[0]["t"], "t_max": events[-1]["t"],
        "x_range": [min(xs), max(xs)], "y_range": [min(ys), max(ys)],
        "z_range": [min(zs), max(zs)],
    }
    return {"meta": meta, "events": events, "meteo": []}

# 8. Synthetic UK traffic incidents
def generate_traffic(n_events=9000, seed=42):
    """Synthetic UK road-accident data with rush-hour temporal patterns."""
    print(f"  Generating {n_events} synthetic traffic incidents ...", end=" ", flush=True)
    rng = np.random.default_rng(seed)

    roads = [
        (np.array([-40000,-28000]), np.array([42000, 30000]), 0.30),
        (np.array([  3000,-36000]), np.array([ 3000, 36000]), 0.25),
        (np.array([-44000,  1000]), np.array([44000,  1000]), 0.22),
        (np.array([-22000,-22000]), np.array([22000, 22000]), 0.13),
        (np.array([-16000, 12000]), np.array([26000,-14000]), 0.10),
    ]
    weights = np.array([r[2] for r in roads]); weights /= weights.sum()
    t_start = 1640995200   # 2022-01-01 00:00 UTC
    events = []

    for _ in range(n_events):
        ri = rng.choice(len(roads), p=weights)
        s, e = roads[ri][0], roads[ri][1]
        direction = e - s
        norm_len = float(np.linalg.norm(direction)) or 1.0
        perp = np.array([-direction[1], direction[0]]) / norm_len
        pos = s + rng.uniform(0, 1)*direction + perp*rng.normal(0, 400)

        day = int(rng.integers(0, 365))
        is_wknd = (day % 7) >= 5
        hr_draw = float(rng.uniform())
        if   is_wknd:         hour = float(rng.normal(12.5, 3.5))
        elif hr_draw < 0.25:  hour = float(rng.normal(8.0,  0.9))
        elif hr_draw < 0.55:  hour = float(rng.normal(17.5, 1.1))
        elif hr_draw < 0.80:  hour = float(rng.uniform(10, 16))
        else:                 hour = float(rng.uniform(0, 6))
        hour = max(0.0, min(23.99, hour))
        ts = t_start + day*86400 + int(hour*3600)
        sev = int(rng.choice([1, 2, 3], p=[0.04, 0.22, 0.74]))
        events.append({"t": float(ts), "x": round(float(pos[0]), 1),
                       "y": round(float(pos[1]), 1), "z": 0.0,
                       "q": round((4 - sev) / 3.0, 4)})

    events.sort(key=lambda ev: ev["t"])
    print(f"{len(events)} events")

    xs = [e["x"] for e in events]; ys = [e["y"] for e in events]
    meta = {
        "name": "UK Road Traffic Incidents (Synthetic)", "domain": "traffic",
        "axes": {"x": "Longitude (proj.)", "y": "Latitude (proj.)", "z": "(flat)"},
        "q_label": "Severity (inverse)", "date_range": "Jan – Dec 2022", "has_meteo": False,
        "count": len(events), "t_min": events[0]["t"], "t_max": events[-1]["t"],
        "x_range": [min(xs), max(xs)], "y_range": [min(ys), max(ys)], "z_range": [0.0, 0.0],
    }
    return {"meta": meta, "events": events, "meteo": []}


# Main

def main():
    parser = argparse.ArgumentParser(
        description="Convert raw CSV datasets -> public/data.js"
    )
    parser.add_argument(
        "--sample", type=int, default=None,
        help="Limit events to N rows  (e.g. --sample 5000 for faster development)"
    )
    args = parser.parse_args()

    print("\n=== convert_data.py ===")
    print(f"Input:  {RAW_DIR}")
    print(f"Output: {OUT_FILE}\n")

    print("[1/8] Events")
    events = convert_events(sample=args.sample)

    print("[2/8] Meteo")
    meteo = convert_meteo()

    print("[3/8] Runoff")
    runoff = convert_runoff()

    print("[4/8] Stations")
    stations = convert_stations()

    print("[5/8] Glacier surface")
    surface = build_surface()

    print("\n[6/8] Writing data.js ...")
    write_data_js(events, meteo, runoff, stations, surface)

    print("\n[7/8] Lorenz attractor")
    write_js_const(OUT_DIR / "data_lorenz.js", "DATASET_LORENZ", generate_lorenz())

    print("\n[8/8] Synthetic traffic")
    write_js_const(OUT_DIR / "data_traffic.js", "DATASET_TRAFFIC", generate_traffic())

    print("\nDone. Open public/index.html in your browser.\n")


if __name__ == "__main__":
    main()