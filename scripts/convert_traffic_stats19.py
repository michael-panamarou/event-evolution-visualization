#!/usr/bin/env python3
"""
convert_traffic_stats19.py
──────────────────────────────────────────────────────────────────────────────
Converts the REAL UK STATS19 collision data into the prototype's unified event
format, replacing the synthetic traffic generator.

Input   data/raw/dft-road-casualty-statistics-collision-provisional-2025.csv
        (Department for Transport, "Road Safety Data", provisional 2025)

Output  public/data_traffic.js   ->  const DATASET_TRAFFIC = { meta, events }

Why this region
    The default bounding box covers Leeds - Manchester - Sheffield together
    with the Peak District and the Pennines. It is the best compromise in the
    2025 provisional file between event count (~4,300 collisions in 6 months)
    and genuine terrain relief (sea level to ~600 m), which is what gives the
    dataset a real third spatial dimension instead of a flat z = 0 plane.

Coordinates
    STATS19 ships both WGS84 lat/lon and OS grid easting/northing in metres.
    The OS grid is used directly: it is already metric and equal-area over a
    region this size, so no projection step is needed. Coordinates are then
    expressed relative to the centre of the region, exactly like the seismic
    dataset's east_shift / north_shift.

Elevation (the third dimension)
    STATS19 has no elevation field. Run fetch_elevation.py first to build
    data/raw/traffic_elevation.csv (collision_index,elevation). If that file
    is missing this script still runs, but writes z = 0 and says so loudly.

Severity -> q
    fatal = 1.0, serious = 0.6, slight = 0.25, so that the most serious
    collisions are the most visually salient, matching the convention used by
    the seismic dataset (higher q = more important).
"""

from __future__ import annotations
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT     = Path(__file__).resolve().parent.parent
RAW_DIR  = ROOT / "data" / "raw"        # inputs, immutable
PROC_DIR = ROOT / "data" / "processed"  # generated by fetch_elevation.py
OUT_DIR  = ROOT / "public"

CSV_NAME = "dft-road-casualty-statistics-collision-provisional-2025.csv"
ELEV_CSV = PROC_DIR / "traffic_elevation.csv"
DEM_JSON = PROC_DIR / "traffic_dem.json"

# Leeds - Manchester - Sheffield + Peak District + Pennines
BBOX = dict(lat_min=53.30, lat_max=53.95, lon_min=-2.45, lon_max=-1.25)

SEVERITY_Q     = {1: 1.00, 2: 0.60, 3: 0.25}
SEVERITY_LABEL = {1: "fatal", 2: "serious", 3: "slight"}


def load_collisions(csv_path: Path) -> pd.DataFrame:
    print(f"  Reading {csv_path.name} ...", end=" ", flush=True)
    # collision_index must be read as a string: pandas infers it as str from
    # the source file but as int64 from the cache, which breaks the join.
    df = pd.read_csv(csv_path, low_memory=False, dtype={"collision_index": str})
    print(f"{len(df)} rows")

    df = df[df.latitude.notna() & df.longitude.notna()]
    df = df[df.latitude.between(BBOX["lat_min"], BBOX["lat_max"]) &
            df.longitude.between(BBOX["lon_min"], BBOX["lon_max"])].copy()
    print(f"  Inside the region bounding box: {len(df)} collisions")

    df["dt"] = pd.to_datetime(df.date + " " + df.time,
                              format="%d/%m/%Y %H:%M", errors="coerce")
    bad = df.dt.isna().sum()
    if bad:
        print(f"  Dropping {bad} rows with an unparseable date/time")
        df = df[df.dt.notna()]
    return df.sort_values("dt").reset_index(drop=True)


def attach_elevation(df: pd.DataFrame) -> tuple[pd.Series, bool]:
    """Joins real elevations if the cache exists; otherwise returns zeros."""
    if not ELEV_CSV.exists():
        print("\n  " + "!" * 68)
        print("  !  No data/raw/traffic_elevation.csv found.")
        print("  !  Writing z = 0 -> the dataset stays FLAT (2D).")
        print("  !  Run scripts/fetch_elevation.py first for a real z axis.")
        print("  " + "!" * 68 + "\n")
        return pd.Series(np.zeros(len(df)), index=df.index), False

    elev = pd.read_csv(ELEV_CSV, dtype={"collision_index": str})
    elev = elev.set_index("collision_index")["elevation"]
    z = df.collision_index.map(elev)
    miss = int(z.isna().sum())
    if miss:
        print(f"  {miss} collisions have no cached elevation -> filled with the median")
        z = z.fillna(z.median())
    print(f"  Elevation: {z.min():.0f} .. {z.max():.0f} m "
          f"(median {z.median():.0f} m, relief {z.max() - z.min():.0f} m)")
    return z, True



def build_dem(df: pd.DataFrame, e0: float, n0: float) -> dict | None:
    """
    Converts the lat/lon terrain grid from fetch_elevation.py into the same
    metric frame as the events, so it can be used as the STC base.

    A linear lat/lon -> OS grid fit is only good to ~87 m RMS over a region
    this size (80 x 72 km), which would visibly shear the terrain. A quadratic
    fit, using the collisions themselves as control points (they carry BOTH
    coordinate systems), is accurate to ~0.3 m RMS.
    """
    if not DEM_JSON.exists():
        print("  No traffic_dem.json - the STC will have no terrain base")
        return None

    dem = json.loads(DEM_JSON.read_text())
    n = int(dem["n"])

    lat = df.latitude.values.astype(float)
    lon = df.longitude.values.astype(float)
    A = np.column_stack([lon, lat, lon * lat, lon ** 2, lat ** 2, np.ones(len(lat))])
    ce, *_ = np.linalg.lstsq(A, df.location_easting_osgr.values.astype(float),  rcond=None)
    cn, *_ = np.linalg.lstsq(A, df.location_northing_osgr.values.astype(float), rcond=None)
    rms_e = float(np.sqrt(np.mean((df.location_easting_osgr.values  - A @ ce) ** 2)))
    rms_n = float(np.sqrt(np.mean((df.location_northing_osgr.values - A @ cn) ** 2)))
    print(f"  lat/lon -> OS grid fit (quadratic): RMS {rms_e:.1f} / {rms_n:.1f} m")

    glat = np.linspace(dem["lat_min"], dem["lat_max"], n)
    glon = np.linspace(dem["lon_min"], dem["lon_max"], n)
    LA, LO = np.meshgrid(glat, glon, indexing="ij")          # row = lat, col = lon
    G = np.column_stack([LO.ravel(), LA.ravel(), (LO * LA).ravel(),
                         (LO ** 2).ravel(), (LA ** 2).ravel(), np.ones(LA.size)])
    gx = (G @ ce - e0).reshape(n, n)
    gy = (G @ cn - n0).reshape(n, n)
    z  = np.asarray(dem["z"], dtype=float).reshape(n, n)

    # The projected grid is very slightly curved; the renderer wants a regular
    # grid, so resample onto one spanning the same area.
    from scipy.interpolate import griddata
    x_lin = np.linspace(gx.min(), gx.max(), n)
    y_lin = np.linspace(gy.min(), gy.max(), n)
    GX, GY = np.meshgrid(x_lin, y_lin)
    zr = griddata(np.column_stack([gx.ravel(), gy.ravel()]), z.ravel(),
                  (GX, GY), method="linear")
    bad = np.isnan(zr)
    if bad.any():
        zr[bad] = griddata(np.column_stack([gx.ravel(), gy.ravel()]), z.ravel(),
                           (GX[bad], GY[bad]), method="nearest")

    print(f"  Terrain base: {n}x{n}, elevation {zr.min():.0f}..{zr.max():.0f} m, "
          f"extent {(x_lin.max()-x_lin.min())/1000:.0f} x {(y_lin.max()-y_lin.min())/1000:.0f} km")
    return {
        "n": n,
        "x_min": round(float(x_lin.min()), 1), "x_max": round(float(x_lin.max()), 1),
        "y_min": round(float(y_lin.min()), 1), "y_max": round(float(y_lin.max()), 1),
        "z_min": round(float(zr.min()), 1),    "z_max": round(float(zr.max()), 1),
        "z": [round(float(v), 1) for v in zr.ravel()],
    }


def build(df: pd.DataFrame, z: pd.Series, has_elev: bool) -> dict:
    # OS grid is already in metres; express relative to the region centre
    e0 = float(df.location_easting_osgr.mean())
    n0 = float(df.location_northing_osgr.mean())
    x = (df.location_easting_osgr  - e0).astype(float)
    y = (df.location_northing_osgr - n0).astype(float)

    # NB: pandas may hold datetimes at microsecond resolution, so astype("int64")
    # is NOT reliably nanoseconds. Subtracting the epoch is resolution-safe.
    t = (df.dt - pd.Timestamp("1970-01-01")) / pd.Timedelta(seconds=1)
    q = df.collision_severity.map(SEVERITY_Q).fillna(0.25)

    events = [
        {"t": round(float(ti), 1), "x": round(float(xi), 1), "y": round(float(yi), 1),
         "z": round(float(zi), 1), "q": round(float(qi), 3)}
        for ti, xi, yi, zi, qi in zip(t, x, y, z, q)
    ]

    counts = df.collision_severity.value_counts().to_dict()
    sev_txt = ", ".join(f"{v} {SEVERITY_LABEL.get(k, k)}" for k, v in sorted(counts.items()))

    meta = {
        "name": "UK Road Collisions 2025 (STATS19, N England)",
        "domain": "traffic",
        "axes": {"x": "East (m)", "y": "North (m)",
                 "z": "Elevation (m)" if has_elev else "(flat)"},
        "q_label": "Severity (fatal > serious > slight)",
        "date_range": f"{df.dt.min():%d %b %Y} - {df.dt.max():%d %b %Y}",
        "has_meteo": False,
        "count": len(events),
        "t_min": float(t.min()), "t_max": float(t.max()),
        "x_range": [round(float(x.min()), 1), round(float(x.max()), 1)],
        "y_range": [round(float(y.min()), 1), round(float(y.max()), 1)],
        "z_range": [round(float(z.min()), 1), round(float(z.max()), 1)],
        "source": "Department for Transport, STATS19 Road Safety Data, "
                  "provisional 2025 (Jan-Jun). Open Government Licence v3.0.",
        "severity_breakdown": sev_txt,
    }
    dem = build_dem(df, e0, n0)
    out = {"meta": meta, "events": events}
    if dem: out["dem"] = dem
    return out


def main() -> int:
    csv_path = RAW_DIR / CSV_NAME
    if not csv_path.exists():
        print(f"ERROR: {csv_path} not found.")
        print("Download 'Road Safety Data - Collisions' from")
        print("https://www.gov.uk/government/statistics/road-safety-data")
        return 1

    print("[1/3] Collisions")
    df = load_collisions(csv_path)

    print("[2/3] Elevation")
    z, has_elev = attach_elevation(df)

    print("[3/3] Writing data_traffic.js")
    ds = build(df, z, has_elev)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / "data_traffic.js"
    out.write_text(
        "// auto-generated by scripts/convert_traffic_stats19.py - do not edit\n"
        "const DATASET_TRAFFIC = " + json.dumps(ds, separators=(",", ":")) + ";\n",
        encoding="utf-8")

    m = ds["meta"]
    print(f"\n  OK  {out}  ({out.stat().st_size/1024:.0f} KB)")
    print(f"      {m['count']} collisions, {m['date_range']}")
    print(f"      severity: {m['severity_breakdown']}")
    print(f"      extent   x {m['x_range']}  y {m['y_range']}  z {m['z_range']} m")
    if not has_elev:
        print("      NOTE: z is flat - run fetch_elevation.py for a real third dimension")
    return 0


if __name__ == "__main__":
    sys.exit(main())